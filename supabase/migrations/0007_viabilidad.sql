-- ZYRA — 0007_viabilidad.sql
-- Módulo de Revisión de Viabilidad Solar.
--
-- Arquitectura aprobada:
--  * Aplicabilidad EXPLÍCITA por proyecto (requiere_previabilidad /
--    requiere_ingenieria), snapshot de viabilidad_config_servicio al crear
--    el proyecto. requiere_viabilidad es una columna DERIVADA.
--  * Plantillas versionadas (nunca se mutan) + revisiones inmutables.
--  * Ciclo de revisión: borrador→en_progreso→evaluada→finalizada (+anulada).
--  * Motor de evaluación por señales, sin "primera coincidencia gana".
--  * Gate server-side fail-closed en validar_checklist e iniciar_proyecto.
--  * Ingeniería exige Previabilidad finalizada con resultado apto.
-- Idempotente: se puede reaplicar sin efectos secundarios.
-- =====================================================================

-- ═════════════════════════════════════════════════════════════════════
-- 1) Aplicabilidad: config por servicio + columnas en proyectos
-- ═════════════════════════════════════════════════════════════════════
create table if not exists viabilidad_config_servicio (
  servicio_id            integer primary key references servicios(id_servicio) on delete cascade,
  requiere_previabilidad boolean not null default false,
  requiere_ingenieria    boolean not null default false,
  activo_desde           date,
  actualizado_en         timestamptz not null default now(),
  constraint chk_vcs_ingenieria_requiere_previabilidad
    check (not (requiere_ingenieria and not requiere_previabilidad))
);

alter table proyectos add column if not exists requiere_previabilidad boolean not null default false;
alter table proyectos add column if not exists requiere_ingenieria    boolean not null default false;
alter table proyectos add column if not exists requiere_viabilidad boolean
  generated always as (requiere_previabilidad or requiere_ingenieria) stored;

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'chk_proyectos_vii_ingenieria_requiere_previabilidad') then
    alter table public.proyectos add constraint chk_proyectos_vii_ingenieria_requiere_previabilidad
      check (not (requiere_ingenieria and not requiere_previabilidad));
  end if;
end $$;

-- Snapshot de la config del servicio al crear el proyecto (fuente de verdad
-- para proyectos nuevos; los históricos quedan en false).
create or replace function public._aplicar_config_viabilidad()
returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_cfg record;
begin
  select requiere_previabilidad, requiere_ingenieria into v_cfg
  from viabilidad_config_servicio where servicio_id = new.servicio_id;
  if found then
    new.requiere_previabilidad := v_cfg.requiere_previabilidad;
    new.requiere_ingenieria    := v_cfg.requiere_ingenieria;
  else
    new.requiere_previabilidad := false;
    new.requiere_ingenieria    := false;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_proyectos_config_viabilidad on public.proyectos;
create trigger trg_proyectos_config_viabilidad
  before insert on public.proyectos
  for each row execute function public._aplicar_config_viabilidad();

