  constraint chk_vcd_operador check (operador in ('=','!=','in','not_in','>=','<=','>','<','contiene')),
  constraint chk_vcd_accion   check (accion in ('mostrar','ocultar','requerir'))
);
create index if not exists idx_vcd_pregunta on viabilidad_condiciones(pregunta_id);

