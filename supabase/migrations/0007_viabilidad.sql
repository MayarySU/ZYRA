-- Referencia/config: lectura general, gestión admin.
do $$
declare t text;
begin
  foreach t in array array['viabilidad_config_servicio','viabilidad_plantillas','viabilidad_secciones',
                           'viabilidad_preguntas','viabilidad_opciones','viabilidad_condiciones'] loop
    execute format('drop policy if exists %1$s_select on %1$s', t);
    execute format('create policy %1$s_select on %1$s for select to authenticated using (true)', t);
    execute format('drop policy if exists %1$s_admin on %1$s', t);
    execute format('create policy %1$s_admin on %1$s for all to authenticated
                    using (public.es_admin()) with check (public.es_admin())', t);
  end loop;
end $$;

-- Revisiones: lectura para admin/miembro/participante; escritura directa admin
-- (las RPC, security definer, hacen el resto). La inmutabilidad la impone el trigger.
drop policy if exists vrv_select on viabilidad_revisiones;
create policy vrv_select on viabilidad_revisiones for select to authenticated
  using (public.es_admin() or public.es_miembro_proyecto(proyecto_id)
         or public.es_participante_viabilidad(id_revision_viabilidad));
drop policy if exists vrv_admin on viabilidad_revisiones;
create policy vrv_admin on viabilidad_revisiones for all to authenticated
  using (public.es_admin()) with check (public.es_admin());

