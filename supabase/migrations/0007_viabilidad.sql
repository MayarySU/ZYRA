create or replace function public._viabilidad_exigir_previabilidad(p_proyecto_id integer)
returns void language plpgsql stable security definer set search_path = public as $$
declare
  v_proy record;
begin
  select * into v_proy from proyectos where id_proyecto = p_proyecto_id;
  if not v_proy.requiere_previabilidad then return; end if;
  if public._viabilidad_plantilla_activa(v_proy.empresa_id, v_proy.servicio_id, 'previabilidad') is null then
    raise exception 'Configuración de viabilidad incompleta: falta plantilla activa de Previabilidad';
  end if;
  if not exists (
    select 1 from viabilidad_revisiones r
    where r.proyecto_id = p_proyecto_id and r.tipo_etapa = 'previabilidad'
      and r.estado = 'finalizada' and r.resultado_final = 'apto'
  ) then
    raise exception 'Previabilidad debe estar finalizada con resultado apto antes de Ingeniería';
  end if;
end;
$$;

-- Gate del proyecto: fail-closed si una etapa requerida carece de plantilla.
create or replace function public._exigir_viabilidad(p_proyecto_id integer)
returns void language plpgsql stable security definer set search_path = public as $$
declare
  v_proy record;
begin
  select * into v_proy from proyectos where id_proyecto = p_proyecto_id;
  if not v_proy.requiere_previabilidad and not v_proy.requiere_ingenieria then
    return;
  end if;
  if v_proy.requiere_previabilidad then
    if public._viabilidad_plantilla_activa(v_proy.empresa_id, v_proy.servicio_id, 'previabilidad') is null then
      raise exception 'Configuración de viabilidad incompleta: falta plantilla activa de Previabilidad';
    end if;
    if not exists (
      select 1 from viabilidad_revisiones r
      where r.proyecto_id = p_proyecto_id and r.tipo_etapa = 'previabilidad'
        and r.estado = 'finalizada' and r.resultado_final = 'apto'
    ) then
      raise exception 'Previabilidad pendiente: complete la revisión de viabilidad';
    end if;
  end if;
  if v_proy.requiere_ingenieria then
    if public._viabilidad_plantilla_activa(v_proy.empresa_id, v_proy.servicio_id, 'ingenieria') is null then
      raise exception 'Configuración de viabilidad incompleta: falta plantilla activa de Ingeniería';
    end if;
    if not exists (
      select 1 from viabilidad_revisiones r
      where r.proyecto_id = p_proyecto_id and r.tipo_etapa = 'ingenieria'
        and r.estado = 'finalizada' and r.resultado_final = 'apto'
    ) then
      raise exception 'Validación de ingeniería pendiente: complete la revisión de viabilidad';
    end if;
  end if;
end;
$$;

