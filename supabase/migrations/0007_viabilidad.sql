create table if not exists viabilidad_condiciones (
  id_condicion_viabilidad integer generated by default as identity primary key,
  pregunta_id             integer not null references viabilidad_preguntas(id_pregunta_viabilidad) on delete cascade,
  pregunta_origen_id      integer not null references viabilidad_preguntas(id_pregunta_viabilidad) on delete cascade,
  operador                text not null,
  valor                   text,
