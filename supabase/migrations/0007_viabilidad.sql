-- ═════════════════════════════════════════════════════════════════════
-- 5) Inmutabilidad y guardias
-- ═════════════════════════════════════════════════════════════════════
-- 5.a Revisión: una vez finalizada o anulada, no admite NINGÚN cambio
--     (sin excepción para admin). Las transiciones HACIA finalizada/anulada
--     tienen OLD.estado distinto, por eso siguen permitidas.
create or replace function public._proteger_revision_viabilidad()
returns trigger language plpgsql as $$
begin
  if old.estado in ('finalizada','anulada') then
    raise exception 'La revisión está % y es inmutable', old.estado;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_vrv_inmutable on public.viabilidad_revisiones;
create trigger trg_vrv_inmutable
  before update on public.viabilidad_revisiones
  for each row execute function public._proteger_revision_viabilidad();

-- 5.b Respuestas: solo mutables mientras el cuestionario está abierto.
create or replace function public._proteger_respuestas_viabilidad()
returns trigger language plpgsql as $$
declare
  v_estado text;
begin
  select estado into v_estado from viabilidad_revisiones
   where id_revision_viabilidad = coalesce(new.revision_id, old.revision_id);
  if v_estado not in ('borrador','en_progreso') then
    raise exception 'El cuestionario ya fue entregado (estado %) y no admite cambios', v_estado;
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists trg_vre_protegida on public.viabilidad_respuestas;
create trigger trg_vre_protegida
  before insert or update or delete on public.viabilidad_respuestas
  for each row execute function public._proteger_respuestas_viabilidad();

-- 5.c Acciones/validaciones: solo mutables en la fase de resolución (evaluada).
create or replace function public._proteger_obligaciones_viabilidad()
returns trigger language plpgsql as $$
declare
  v_estado text;
begin
  select estado into v_estado from viabilidad_revisiones
   where id_revision_viabilidad = coalesce(new.revision_id, old.revision_id);
  if v_estado <> 'evaluada' then
    raise exception 'Las obligaciones solo son editables durante la resolución (estado actual %)', v_estado;
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists trg_vac_protegida on public.viabilidad_acciones;
create trigger trg_vac_protegida
  before insert or update or delete on public.viabilidad_acciones
  for each row execute function public._proteger_obligaciones_viabilidad();
drop trigger if exists trg_vvl_protegida on public.viabilidad_validaciones;
create trigger trg_vvl_protegida
  before insert or update or delete on public.viabilidad_validaciones
  for each row execute function public._proteger_obligaciones_viabilidad();

-- 5.d Evidencias: solo hasta que la revisión quede finalizada/anulada.
create or replace function public._proteger_evidencias_viabilidad()
returns trigger language plpgsql as $$
declare
  v_estado text;
begin
  select estado into v_estado from viabilidad_revisiones
   where id_revision_viabilidad = coalesce(new.revision_id, old.revision_id);
  if v_estado in ('finalizada','anulada') then
    raise exception 'La revisión está % y no admite evidencias', v_estado;
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists trg_vve_protegida on public.viabilidad_evidencias;
create trigger trg_vve_protegida
  before insert or update or delete on public.viabilidad_evidencias
  for each row execute function public._proteger_evidencias_viabilidad();

-- 5.e Aplicabilidad: una vez iniciada una etapa, no puede cambiarse (evita
--     ponerla en false para saltarse el gate).
create or replace function public._proteger_aplicabilidad_viabilidad()
returns trigger language plpgsql as $$
begin
  if new.requiere_previabilidad is distinct from old.requiere_previabilidad
     and exists (select 1 from viabilidad_revisiones r
                 where r.proyecto_id = old.id_proyecto and r.tipo_etapa = 'previabilidad') then
    raise exception 'La aplicabilidad de Previabilidad no puede cambiarse: ya existe una revisión';
  end if;
  if new.requiere_ingenieria is distinct from old.requiere_ingenieria
     and exists (select 1 from viabilidad_revisiones r
                 where r.proyecto_id = old.id_proyecto and r.tipo_etapa = 'ingenieria') then
    raise exception 'La aplicabilidad de Ingeniería no puede cambiarse: ya existe una revisión';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_proyectos_aplicabilidad on public.proyectos;
create trigger trg_proyectos_aplicabilidad
  before update on public.proyectos
  for each row execute function public._proteger_aplicabilidad_viabilidad();

-- ═════════════════════════════════════════════════════════════════════
-- 6) Motor de evaluación (señales + precedencia)
-- ═════════════════════════════════════════════════════════════════════
create or replace function public._viabilidad_condicion_cumple(p_valor jsonb, p_operador text, p_texto text)
returns boolean language plpgsql immutable as $$
declare
  v_es_array boolean := (jsonb_typeof(p_valor) = 'array');
  v_txt text;
  v_num numeric;
  v_pnum numeric;
begin
  if p_valor is null or p_valor = 'null'::jsonb then return false; end if;
  v_txt := case when jsonb_typeof(p_valor) = 'string' then p_valor #>> '{}' else p_valor::text end;

  if p_operador in ('>','>=','<','<=') then
    begin v_num := v_txt::numeric; exception when others then v_num := null; end;
    begin v_pnum := p_texto::numeric; exception when others then v_pnum := null; end;
    if v_num is null or v_pnum is null then return false; end if;
    return case p_operador
      when '>'  then v_num >  v_pnum
      when '>=' then v_num >= v_pnum
      when '<'  then v_num <  v_pnum
      when '<=' then v_num <= v_pnum
    end;
  end if;

  return case p_operador
    when '='     then (v_es_array and p_valor ? p_texto) or (not v_es_array and v_txt = p_texto)
    when '!='    then not ((v_es_array and p_valor ? p_texto) or (not v_es_array and v_txt = p_texto))
    when 'contiene' then position(lower(p_texto) in lower(v_txt)) > 0 or (v_es_array and p_valor ? p_texto)
    when 'in'     then v_txt = any(string_to_array(p_texto, ','))
    when 'not_in' then not (v_txt = any(string_to_array(p_texto, ',')))
    else false
  end;
end;
$$;

create or replace function public._viabilidad_respuesta_activa(p_valor jsonb, p_tipo text)
returns boolean language sql immutable as $$
  select case
    when p_valor is null or p_valor = 'null'::jsonb then false
    when p_tipo = 'booleano'        then (p_valor = 'true'::jsonb)
    when p_tipo = 'opcion_multiple' then (jsonb_typeof(p_valor) = 'array' and jsonb_array_length(p_valor) > 0)
    when p_tipo = 'opcion_unica'    then (jsonb_typeof(p_valor) = 'string' and (p_valor #>> '{}') <> '')
    when p_tipo = 'texto'           then (jsonb_typeof(p_valor) = 'string' and (p_valor #>> '{}') <> '')
    when p_tipo in ('numero','fecha') then (jsonb_typeof(p_valor) in ('number','string') and (p_valor #>> '{}') <> '')
    else true
  end;
$$;

create or replace function public._viabilidad_pregunta_visible(p_revision_id integer, p_pregunta_id integer)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare
  v_tiene_mostrar boolean;
  v_mostrar_ok boolean := false;
  v_oculto boolean := false;
  c record;
  v_valor jsonb;
begin
  select exists(select 1 from viabilidad_condiciones
                where pregunta_id = p_pregunta_id and accion = 'mostrar') into v_tiene_mostrar;

  for c in select * from viabilidad_condiciones where pregunta_id = p_pregunta_id loop
    select valor into v_valor from viabilidad_respuestas
     where revision_id = p_revision_id and pregunta_id = c.pregunta_origen_id;
    if public._viabilidad_condicion_cumple(v_valor, c.operador, c.valor) then
      if c.accion = 'mostrar' then v_mostrar_ok := true;
      elsif c.accion = 'ocultar' then v_oculto := true;
      end if;
    end if;
  end loop;

  if v_oculto then return false; end if;
  if v_tiene_mostrar then return v_mostrar_ok; end if;
  return true;
end;
$$;

create or replace function public._viabilidad_pregunta_requerida(
  p_revision_id integer, p_pregunta_id integer, p_obligatoria boolean
) returns boolean language sql stable security definer set search_path = public as $$
  select p_obligatoria
      or exists (
        select 1 from viabilidad_condiciones c
        where c.pregunta_id = p_pregunta_id and c.accion = 'requerir'
          and public._viabilidad_condicion_cumple(
                (select valor from viabilidad_respuestas
                 where revision_id = p_revision_id and pregunta_id = c.pregunta_origen_id),
                c.operador, c.valor)
      );
$$;

create or replace function public._viabilidad_senales(p_revision_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_senales jsonb := '[]'::jsonb;
  r record;
  op record;
  v_sel boolean;
  v_regla jsonb;
begin
  for r in
    select resp.valor, resp.pregunta_id, p.tipo_respuesta, p.regla_evaluacion, p.codigo
    from viabilidad_respuestas resp
    join viabilidad_preguntas p on p.id_pregunta_viabilidad = resp.pregunta_id
    where resp.revision_id = p_revision_id
  loop
    for op in select valor, regla from viabilidad_opciones
              where pregunta_id = r.pregunta_id and regla is not null loop
      if r.tipo_respuesta = 'opcion_unica' then
        v_sel := (r.valor = to_jsonb(op.valor));
      elsif r.tipo_respuesta = 'opcion_multiple' then
        v_sel := (jsonb_typeof(r.valor) = 'array' and r.valor ? op.valor);
      else
        v_sel := false;
      end if;
      if v_sel then
        v_senales := v_senales || jsonb_build_array(op.regla || jsonb_build_object('pregunta', r.codigo));
      end if;
    end loop;

    if r.regla_evaluacion is not null then
      if r.regla_evaluacion ? 'cuando' then
        v_regla := r.regla_evaluacion;
        if public._viabilidad_condicion_cumple(
             r.valor, v_regla->'cuando'->>'operador', v_regla->'cuando'->>'valor') then
          v_senales := v_senales || jsonb_build_array(v_regla - 'cuando' || jsonb_build_object('pregunta', r.codigo));
        end if;
      elsif public._viabilidad_respuesta_activa(r.valor, r.tipo_respuesta) then
        v_senales := v_senales || jsonb_build_array(r.regla_evaluacion || jsonb_build_object('pregunta', r.codigo));
      end if;
    end if;
  end loop;
  return v_senales;
end;
$$;

create or replace function public._viabilidad_resultado(p_senales jsonb)
returns text language sql immutable as $$
  select case
    when exists (select 1 from jsonb_array_elements(p_senales) s where s->>'efecto' = 'no_apto')               then 'no_apto'
    when exists (select 1 from jsonb_array_elements(p_senales) s where s->>'efecto' = 'validacion_especializada') then 'requiere_validacion'
    when exists (select 1 from jsonb_array_elements(p_senales) s where s->>'efecto' = 'accion_requerida')      then 'apto_con_acciones'
    else 'apto'
  end;
$$;

create or replace function public._viabilidad_validar_obligatorias(p_revision_id integer)
returns void language plpgsql stable security definer set search_path = public as $$
declare
  v_rev record;
  p record;
begin
  select * into v_rev from viabilidad_revisiones where id_revision_viabilidad = p_revision_id;
  for p in
    select pg.id_pregunta_viabilidad, pg.codigo, pg.obligatoria
    from viabilidad_preguntas pg
    join viabilidad_secciones s on s.id_seccion_viabilidad = pg.seccion_id
    where s.plantilla_id = v_rev.plantilla_id and pg.activa = true
  loop
    if public._viabilidad_pregunta_visible(p_revision_id, p.id_pregunta_viabilidad)
       and public._viabilidad_pregunta_requerida(p_revision_id, p.id_pregunta_viabilidad, p.obligatoria) then
      if not exists (
        select 1 from viabilidad_respuestas r
        where r.revision_id = p_revision_id and r.pregunta_id = p.id_pregunta_viabilidad
          and r.valor is not null and r.valor <> 'null'::jsonb
          and (jsonb_typeof(r.valor) <> 'string' or (r.valor #>> '{}') <> '')
          and (jsonb_typeof(r.valor) <> 'array' or jsonb_array_length(r.valor) > 0)
      ) then
        raise exception 'Falta responder la pregunta obligatoria "%"', p.codigo;
      end if;
    end if;
  end loop;
end;
$$;

create or replace function public.evaluar_viabilidad(p_revision_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_senales jsonb;
begin
  if not exists (select 1 from viabilidad_revisiones where id_revision_viabilidad = p_revision_id) then
    raise exception 'Revisión % no existe', p_revision_id;
  end if;
  if not (public.es_admin() or public.es_participante_viabilidad(p_revision_id)) then
    raise exception 'Sin permiso sobre la revisión %', p_revision_id;
  end if;
  v_senales := public._viabilidad_senales(p_revision_id);
  return jsonb_build_object('resultado', public._viabilidad_resultado(v_senales), 'senales', v_senales);
end;
$$;

