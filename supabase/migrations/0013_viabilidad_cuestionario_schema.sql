create table if not exists viabilidad_reglas (
  id_regla_viabilidad integer generated by default as identity primary key,
  plantilla_id         integer not null references viabilidad_plantillas(id_plantilla_viabilidad) on delete cascade,
  orden                integer not null default 0,
  etiqueta             text,
  codigo               text not null,
  severidad_funcional  text not null,
  efecto_funcional     text not null,
  cuando               jsonb not null,
  mensaje              text,
  accion_o_tipo        text,
  validacion_tipo      text,
  creado_en            timestamptz not null default now(),
  constraint chk_vrg_severidad check (severidad_funcional in
    ('bloqueante','requiere_especialista','observacion','informativa')),
  constraint chk_vrg_efecto check (efecto_funcional in
    ('no_apto','validacion_especializada','accion_requerida','observacion','informativa')),
  constraint chk_vrg_validacion check (validacion_tipo is null or validacion_tipo in
    ('estructural','electrico','legal','cfe','otro')),
  unique (plantilla_id, codigo)
);
create index if not exists idx_vrg_plantilla on viabilidad_reglas(plantilla_id);

