-- ═════════════════════════════════════════════════════════════════════
-- 4) Inmutabilidad de viabilidad_reglas (comparte la guardia de estructura)
-- ═════════════════════════════════════════════════════════════════════
create or replace function public._proteger_estructura_plantilla_viabilidad()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_plantilla integer;
  v_estado text;
begin
  if public._viabilidad_bypass_plantilla() then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;

  if tg_table_name = 'viabilidad_secciones' then
    v_plantilla := coalesce(new.plantilla_id, old.plantilla_id);
  elsif tg_table_name = 'viabilidad_reglas' then
    v_plantilla := coalesce(new.plantilla_id, old.plantilla_id);
  elsif tg_table_name = 'viabilidad_preguntas' then
    select plantilla_id into v_plantilla from viabilidad_secciones
     where id_seccion_viabilidad = coalesce(new.seccion_id, old.seccion_id);
  else -- viabilidad_opciones / viabilidad_condiciones
    select s.plantilla_id into v_plantilla
      from viabilidad_preguntas p
      join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
     where p.id_pregunta_viabilidad = coalesce(new.pregunta_id, old.pregunta_id);
  end if;

  if v_plantilla is null then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;

  select estado into v_estado from viabilidad_plantillas
   where id_plantilla_viabilidad = v_plantilla;

  if v_estado is distinct from 'borrador' then
    raise exception 'La estructura de una plantilla % es inmutable; cree una nueva versión', v_estado;
  end if;
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists trg_viabilidad_reglas_estructura on public.viabilidad_reglas;
create trigger trg_viabilidad_reglas_estructura
  before insert or update or delete on public.viabilidad_reglas
  for each row execute function public._proteger_estructura_plantilla_viabilidad();

-- ═════════════════════════════════════════════════════════════════════
-- 5) Motor: condición (is_null/is_not_null), visibilidad AND, expresiones
-- ═════════════════════════════════════════════════════════════════════
create or replace function public._viabilidad_condicion_cumple(p_valor jsonb, p_operador text, p_texto text)
returns boolean language plpgsql immutable as $$
declare
  v_es_array boolean := (jsonb_typeof(p_valor) = 'array');
  v_txt text;
  v_num numeric;
  v_pnum numeric;
begin
  if p_operador = 'is_null' then
    return p_valor is null or p_valor = 'null'::jsonb;
  end if;
  if p_operador = 'is_not_null' then
    return not (p_valor is null or p_valor = 'null'::jsonb);
  end if;

  if p_valor is null or p_valor = 'null'::jsonb then return false; end if;
  v_txt := case when jsonb_typeof(p_valor) = 'string' then p_valor #>> '{}' else p_valor::text end;

  if p_operador in ('>','>=','<','<=') then
    begin v_num := v_txt::numeric; exception when others then v_num := null; end;
    begin v_pnum := p_texto::numeric; exception when others then v_pnum := null; end;
    if v_num is null or v_pnum is null then return false; end if;
    return case p_operador
      when '>'  then v_num >  v_pnum
      when '>=' then v_num >= v_pnum
      when '<'  then v_num <  v_pnum
      when '<=' then v_num <= v_pnum
    end;
  end if;

  return case p_operador
    when '='     then (v_es_array and p_valor ? p_texto) or (not v_es_array and v_txt = p_texto)
    when '!='    then not ((v_es_array and p_valor ? p_texto) or (not v_es_array and v_txt = p_texto))
    when 'contiene' then position(lower(p_texto) in lower(v_txt)) > 0 or (v_es_array and p_valor ? p_texto)
    when 'in'     then v_txt = any(string_to_array(p_texto, ','))
    when 'not_in' then not (v_txt = any(string_to_array(p_texto, ',')))
    else false
  end;
end;
$$;

-- Visibilidad: múltiples condiciones 'mostrar' => AND. 'ocultar' tiene prioridad.
create or replace function public._viabilidad_pregunta_visible(p_revision_id integer, p_pregunta_id integer)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare
  v_tiene_mostrar boolean;
  v_mostrar_ok boolean := true;
  v_oculto boolean := false;
  c record;
  v_valor jsonb;
begin
  select exists(select 1 from viabilidad_condiciones
                where pregunta_id = p_pregunta_id and accion = 'mostrar') into v_tiene_mostrar;

  for c in select * from viabilidad_condiciones where pregunta_id = p_pregunta_id loop
    select valor into v_valor from viabilidad_respuestas
     where revision_id = p_revision_id and pregunta_id = c.pregunta_origen_id;
    if public._viabilidad_condicion_cumple(v_valor, c.operador, c.valor) then
      if c.accion = 'ocultar' then v_oculto := true; end if;
    else
      if c.accion = 'mostrar' then v_mostrar_ok := false; end if;
    end if;
  end loop;

  if v_oculto then return false; end if;
  if v_tiene_mostrar then return v_mostrar_ok; end if;
  return true;
end;
$$;

-- Evaluador recursivo de expresiones de regla / condicion de evidencia.
-- Nodo hoja: {"pregunta": codigo, "operador": op, "valor": texto?}
-- Nodo compuesto: {"and":[..]} | {"or":[..]} | {"not":{..}}
create or replace function public._viabilidad_expr_cumple(p_revision_id integer, p_expr jsonb)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare
  e jsonb;
  v_resp jsonb;
begin
  if p_expr is null then return true; end if;

  if p_expr ? 'and' then
    for e in select jsonb_array_elements(p_expr->'and') loop
      if not public._viabilidad_expr_cumple(p_revision_id, e) then return false; end if;
    end loop;
    return true;
  end if;
  if p_expr ? 'or' then
    for e in select jsonb_array_elements(p_expr->'or') loop
      if public._viabilidad_expr_cumple(p_revision_id, e) then return true; end if;
    end loop;
    return false;
  end if;
  if p_expr ? 'not' then
    return not public._viabilidad_expr_cumple(p_revision_id, p_expr->'not');
  end if;

  select r.valor into v_resp
    from viabilidad_respuestas r
    join viabilidad_preguntas p on p.id_pregunta_viabilidad = r.pregunta_id
   where r.revision_id = p_revision_id and p.codigo = p_expr->>'pregunta'
   limit 1;
  return public._viabilidad_condicion_cumple(v_resp, p_expr->>'operador', p_expr->>'valor');
end;
$$;

-- Señales: reglas por respuesta/opción (existentes) + reglas a nivel plantilla.
create or replace function public._viabilidad_senales(p_revision_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_senales jsonb := '[]'::jsonb;
  v_plantilla integer;
  r record;
  op record;
  rl record;
  v_sel boolean;
  v_regla jsonb;
begin
  select plantilla_id into v_plantilla from viabilidad_revisiones
   where id_revision_viabilidad = p_revision_id;

  for r in
    select resp.valor, resp.pregunta_id, p.tipo_respuesta, p.regla_evaluacion, p.codigo
    from viabilidad_respuestas resp
    join viabilidad_preguntas p on p.id_pregunta_viabilidad = resp.pregunta_id
    where resp.revision_id = p_revision_id
  loop
    for op in select valor, regla from viabilidad_opciones
              where pregunta_id = r.pregunta_id and regla is not null loop
      if r.tipo_respuesta = 'opcion_unica' then
        v_sel := (r.valor = to_jsonb(op.valor));
      elsif r.tipo_respuesta = 'opcion_multiple' then
        v_sel := (jsonb_typeof(r.valor) = 'array' and r.valor ? op.valor);
      else
        v_sel := false;
      end if;
      if v_sel then
        v_senales := v_senales || jsonb_build_array(op.regla || jsonb_build_object('pregunta', r.codigo));
      end if;
    end loop;

    if r.regla_evaluacion is not null then
      if r.regla_evaluacion ? 'cuando' then
        v_regla := r.regla_evaluacion;
        if public._viabilidad_condicion_cumple(
             r.valor, v_regla->'cuando'->>'operador', v_regla->'cuando'->>'valor') then
          v_senales := v_senales || jsonb_build_array(v_regla - 'cuando' || jsonb_build_object('pregunta', r.codigo));
        end if;
      elsif public._viabilidad_respuesta_activa(r.valor, r.tipo_respuesta) then
        v_senales := v_senales || jsonb_build_array(r.regla_evaluacion || jsonb_build_object('pregunta', r.codigo));
      end if;
    end if;
  end loop;

  for rl in
    select * from viabilidad_reglas
     where plantilla_id = v_plantilla
     order by orden, id_regla_viabilidad
  loop
    if public._viabilidad_expr_cumple(p_revision_id, rl.cuando) then
      v_senales := v_senales || jsonb_build_array(jsonb_strip_nulls(jsonb_build_object(
        'efecto', rl.efecto_funcional,
        'motivo', case when rl.efecto_funcional = 'no_apto' then rl.mensaje else null end,
        'mensaje', rl.mensaje,
        'descripcion_accion',
          case when rl.efecto_funcional in ('no_apto','accion_requerida','observacion')
                    and rl.accion_o_tipo is not null and rl.accion_o_tipo <> 'no_aplica'
               then rl.accion_o_tipo else null end,
        'validacion_tipo',
          case when rl.efecto_funcional = 'validacion_especializada' then rl.accion_o_tipo else null end,
        'regla', rl.codigo
      )));
    end if;
  end loop;

  return v_senales;
end;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- 6) Obligatoriedad de evidencia + validación en la entrega
-- ═════════════════════════════════════════════════════════════════════
create or replace function public._viabilidad_evidencia_obligatoria(p_revision_id integer, p_pregunta_id integer)
returns boolean language plpgsql stable security definer set search_path = public as $$
declare
  p record;
begin
  select evidencia_tipo, evidencia_obligatoria, evidencia_obligatoria_condicion
    into p from viabilidad_preguntas where id_pregunta_viabilidad = p_pregunta_id;
  if not found or p.evidencia_tipo is null then return false; end if;
  if p.evidencia_obligatoria_condicion is not null then
    return public._viabilidad_expr_cumple(p_revision_id, p.evidencia_obligatoria_condicion);
  end if;
  return coalesce(p.evidencia_obligatoria, false);
end;
$$;

create or replace function public._viabilidad_validar_evidencias(p_revision_id integer)
returns void language plpgsql stable security definer set search_path = public as $$
declare
  v_rev record;
  p record;
begin
  select * into v_rev from viabilidad_revisiones where id_revision_viabilidad = p_revision_id;
  for p in
    select pg.id_pregunta_viabilidad, pg.codigo
    from viabilidad_preguntas pg
    join viabilidad_secciones s on s.id_seccion_viabilidad = pg.seccion_id
    where s.plantilla_id = v_rev.plantilla_id and pg.activa = true
  loop
    if public._viabilidad_pregunta_visible(p_revision_id, p.id_pregunta_viabilidad)
       and public._viabilidad_evidencia_obligatoria(p_revision_id, p.id_pregunta_viabilidad) then
      if not exists (
        select 1
        from viabilidad_evidencias ve
        join viabilidad_respuestas r on r.id_respuesta_viabilidad = ve.respuesta_id
        where ve.revision_id = p_revision_id and r.pregunta_id = p.id_pregunta_viabilidad
      ) then
        raise exception 'Falta evidencia obligatoria de la pregunta "%"', p.codigo;
      end if;
    end if;
  end loop;
end;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- 7) Resolución de plantilla: específica → global
-- ═════════════════════════════════════════════════════════════════════
create or replace function public._viabilidad_plantilla_activa(p_empresa_id integer, p_servicio_id integer, p_tipo_etapa text)
returns integer language sql stable security definer set search_path = public as $$
  select id_plantilla_viabilidad from (
    select id_plantilla_viabilidad, 1 as pref, version
    from viabilidad_plantillas
    where empresa_id = p_empresa_id
      and servicio_id is not distinct from p_servicio_id
      and tipo_etapa = p_tipo_etapa
      and estado = 'activa'
    union all
    select id_plantilla_viabilidad, 0 as pref, version
    from viabilidad_plantillas
    where empresa_id = p_empresa_id
      and servicio_id is null
      and p_servicio_id is not null
      and tipo_etapa = p_tipo_etapa
      and estado = 'activa'
  ) t
  order by pref desc, version desc
  limit 1;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- 8) Entregar: exige evidencias obligatorias (además de respuestas)
--    (rederfinición de la versión endurecida en 0011)
-- ═════════════════════════════════════════════════════════════════════
create or replace function public.entregar_revision_viabilidad(
  p_revision_id integer,
  p_operation_id uuid default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_cached jsonb;
  v_rev record;
  v_senales jsonb;
  v_resultado text;
  v_estado_final text;
  v_pend integer;
begin
  perform set_config('zyra.rpc_viabilidad', 'on', true);
  if p_operation_id is not null then
    v_cached := public._idempotente_leer(p_operation_id);
    if v_cached is not null then return v_cached; end if;
  end if;

  select * into v_rev from viabilidad_revisiones where id_revision_viabilidad = p_revision_id;
  if not found then raise exception 'Revisión % no existe', p_revision_id; end if;
  if not (public.es_admin()
          or (v_rev.asignado_empleado_id is not null
              and v_rev.asignado_empleado_id = public.mi_empleado_id())) then
    raise exception 'Sin permiso sobre la revisión %', p_revision_id;
  end if;
  if v_rev.estado not in ('borrador','en_progreso') then
    raise exception 'La revisión no admite entrega en estado %', v_rev.estado;
  end if;

  perform public._viabilidad_validar_obligatorias(p_revision_id);
  perform public._viabilidad_validar_evidencias(p_revision_id);

  v_senales := public._viabilidad_senales(p_revision_id);
  v_resultado := public._viabilidad_resultado(v_senales);

  update viabilidad_revisiones
     set estado = 'evaluada', resultado_evaluacion = v_resultado, resultado_calculado = v_senales,
         evaluada_por = public.mi_empleado_id(), evaluada_en = now(), version = version + 1
   where id_revision_viabilidad = p_revision_id;

  if v_resultado in ('apto_con_acciones','requiere_validacion') then
    insert into viabilidad_acciones(revision_id, descripcion, obligatoria)
    select p_revision_id, x.descripcion, coalesce(x.obligatoria, true)
    from (
      select distinct coalesce(s->>'descripcion_accion', s->>'mensaje') as descripcion,
             (s->>'obligatoria')::boolean as obligatoria
      from jsonb_array_elements(v_senales) s
      where s->>'efecto' = 'accion_requerida'
        and coalesce(s->>'descripcion_accion', s->>'mensaje') is not null
    ) x
    where not exists (select 1 from viabilidad_acciones a
                      where a.revision_id = p_revision_id and a.descripcion = x.descripcion);

    insert into viabilidad_validaciones(revision_id, tipo, creada_por)
    select p_revision_id, x.tipo, public.mi_empleado_id()
    from (
      select distinct s->>'validacion_tipo' as tipo
      from jsonb_array_elements(v_senales) s
      where s->>'efecto' = 'validacion_especializada' and s->>'validacion_tipo' is not null
    ) x
    where not exists (select 1 from viabilidad_validaciones v
                      where v.revision_id = p_revision_id and v.tipo = x.tipo);
  end if;

  select (select count(*) from viabilidad_acciones
           where revision_id = p_revision_id and obligatoria and estado <> 'validada')
       + (select count(*) from viabilidad_validaciones
           where revision_id = p_revision_id and estado = 'pendiente')
    into v_pend;

  if v_pend = 0 then
    update viabilidad_revisiones
       set estado = 'finalizada',
           resultado_final = case when v_resultado = 'no_apto' then 'no_apto' else 'apto' end,
           finalizada_por = public.mi_empleado_id(), finalizada_en = now(), version = version + 1
     where id_revision_viabilidad = p_revision_id;
    v_estado_final := 'finalizada';
  else
    v_estado_final := 'evaluada';
  end if;

  insert into audit_log(usuario_id, empleado_id, accion, entidad, entidad_id, valores_nuevos)
  values (auth.uid(), public.mi_empleado_id(), 'entregar_revision_viabilidad', 'viabilidad_revisiones',
          p_revision_id::text, jsonb_build_object('resultado', v_resultado, 'estado', v_estado_final));

  v_cached := jsonb_build_object('id_revision_viabilidad', p_revision_id,
    'estado', v_estado_final, 'resultado_evaluacion', v_resultado);
  if p_operation_id is not null then
    perform public._idempotente_guardar(p_operation_id, 'entregar_revision_viabilidad', v_cached);
  end if;
  return v_cached;
end;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- 8.b) Validación de expresiones y overrides de validación/versionado
-- ═════════════════════════════════════════════════════════════════════

-- Gramática de una expresión de regla / condición de evidencia.
--   hoja:     {"pregunta": text, "operador": op, "valor": text?}
--   compuesta:{"and":[..]} | {"or":[..]} | {"not":{..}}
-- Devuelve text (null si es válida).
create or replace function public._viabilidad_expr_error(p_expr jsonb, p_codigos text[])
returns text language plpgsql immutable as $$
declare
  v_ops text[] := array['=','!=','in','not_in','>=','<=','>','<','contiene','is_null','is_not_null'];
  k text;
  e jsonb;
  v_preg text;
  v_op text;
  v_errores text[] := array[]::text[];
begin
  if p_expr is null then return 'La expresión es nula'; end if;
  if jsonb_typeof(p_expr) <> 'object' then
    return 'La expresión debe ser un objeto JSON';
  end if;

  if p_expr ? 'and' or p_expr ? 'or' then
    for k in select jsonb_object_keys(p_expr) loop
      if k not in ('and','or') then return format('Nodo compuesto con campo inesperado "%s"', k); end if;
    end loop;
    if jsonb_typeof(coalesce(p_expr->'and', p_expr->'or')) <> 'array'
       or jsonb_array_length(coalesce(p_expr->'and', p_expr->'or')) = 0 then
      return 'El nodo "and"/"or" requiere un arreglo no vacío';
    end if;
    for e in select jsonb_array_elements(coalesce(p_expr->'and', p_expr->'or')) loop
      v_errores := v_errores || public._viabilidad_expr_error(e, p_codigos);
    end loop;
    return nullif(array_to_string(v_errores, '; '), '');
  end if;

  if p_expr ? 'not' then
    for k in select jsonb_object_keys(p_expr) loop
      if k <> 'not' then return format('Nodo "not" con campo inesperado "%s"', k); end if;
    end loop;
    return public._viabilidad_expr_error(p_expr->'not', p_codigos);
  end if;

  -- Hoja
  for k in select jsonb_object_keys(p_expr) loop
    if k not in ('pregunta','operador','valor') then
      return format('La condición usa un campo no soportado ("%s")', k);
    end if;
  end loop;
  v_preg := p_expr->>'pregunta';
  v_op := p_expr->>'operador';
  if v_preg is null or btrim(v_preg) = '' then return 'La condición no define "pregunta"'; end if;
  if v_op is null or not (v_op = any(v_ops)) then
    return format('Operador de condición no soportado: "%s"', coalesce(v_op,'(nulo)'));
  end if;
  if v_op not in ('is_null','is_not_null') and (p_expr->>'valor') is null then
    return format('La condición "%s" con operador "%s" requiere "valor"', v_preg, v_op);
  end if;
  if p_codigos is not null and not (v_preg = any(p_codigos)) then
    return format('La condición referencia la pregunta inexistente "%s"', v_preg);
  end if;
  return null;
end;
$$;

-- Extiende la gramática de reglas por pregunta/opción con observacion/informativa
-- y admite is_null/is_not_null en "cuando".
create or replace function public._viabilidad_regla_error(p_regla jsonb)
returns text language plpgsql immutable as $$
declare
  v_efectos text[] := array['no_apto','validacion_especializada','accion_requerida','observacion','informativa'];
  v_valid  text[] := array['estructural','electrico','legal','cfe','otro'];
  v_ops    text[] := array['=','!=','in','not_in','>=','<=','>','<','contiene','is_null','is_not_null'];
  v_claves text[] := array['cuando','efecto','motivo','mensaje','descripcion_accion',
                           'validacion_tipo','obligatoria','pregunta'];
  v_efecto text;
  v_op text;
  k text;
begin
  if p_regla is null then return null; end if;
  if jsonb_typeof(p_regla) <> 'object' then
    return 'La regla debe ser un objeto JSON';
  end if;

  for k in select jsonb_object_keys(p_regla) loop
    if not (k = any(v_claves)) then
      return format('La regla usa un campo no soportado por el editor ("%s"): requiere edición técnica', k);
    end if;
  end loop;

  v_efecto := p_regla->>'efecto';
  if v_efecto is null then
    return 'La regla no define "efecto"';
  end if;
  if not (v_efecto = any(v_efectos)) then
    return format('Efecto no soportado por el motor: "%s"', v_efecto);
  end if;

  if p_regla ? 'cuando' then
    if jsonb_typeof(p_regla->'cuando') <> 'object' then
      return 'La condición de la regla ("cuando") debe ser un objeto';
    end if;
    v_op := p_regla->'cuando'->>'operador';
    if v_op is null then
      return 'La condición de la regla ("cuando") requiere "operador"';
    end if;
    if not (v_op = any(v_ops)) then
      return format('Operador de condición no soportado: "%s"', v_op);
    end if;
    if v_op not in ('is_null','is_not_null') and (p_regla->'cuando'->>'valor') is null then
      return 'La condición de la regla ("cuando") requiere "valor"';
    end if;
  end if;

  if v_efecto = 'validacion_especializada' then
    if (p_regla->>'validacion_tipo') is null then
      return 'El efecto "validacion_especializada" requiere "validacion_tipo"';
    end if;
    if not ((p_regla->>'validacion_tipo') = any(v_valid)) then
      return format('Tipo de validación no soportado: "%s"', p_regla->>'validacion_tipo');
    end if;
  end if;

  if v_efecto in ('accion_requerida','no_apto')
     and coalesce(p_regla->>'descripcion_accion', p_regla->>'mensaje') is null then
    return format('El efecto "%s" requiere "descripcion_accion" o "mensaje"', v_efecto);
  end if;

  return null;
end;
$$;

-- Validación autoritativa de la plantilla (incluye nuevos campos y reglas).
create or replace function public.validar_plantilla_viabilidad(p_plantilla_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_errores jsonb := '[]'::jsonb;
  v_plantilla record;
  v_secciones integer;
  v_preguntas integer;
  v_dup text;
  v_ciclo boolean;
  v_codigos text[];
  rec record;
  v_err text;
  v_val text;
begin
  select * into v_plantilla from viabilidad_plantillas
   where id_plantilla_viabilidad = p_plantilla_id;
  if not found then
    return jsonb_build_object('ok', false, 'errores',
      jsonb_build_array(jsonb_build_object('codigo','no_existe','mensaje','La plantilla no existe')));
  end if;

  if v_plantilla.tipo_etapa not in ('previabilidad','ingenieria') then
    v_errores := v_errores || jsonb_build_array(jsonb_build_object(
      'codigo','etapa_invalida','mensaje','La etapa de la plantilla es inválida'));
  end if;

  select count(*) into v_secciones from viabilidad_secciones where plantilla_id = p_plantilla_id;
  if v_secciones = 0 then
    v_errores := v_errores || jsonb_build_array(jsonb_build_object(
      'codigo','sin_secciones','mensaje','La plantilla no tiene secciones'));
  end if;

  for rec in select * from viabilidad_secciones where plantilla_id = p_plantilla_id loop
    if rec.titulo is null or btrim(rec.titulo) = '' then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','seccion_sin_titulo','ref', rec.id_seccion_viabilidad::text,
        'mensaje','Hay una sección sin título'));
    end if;
  end loop;

  select count(*) into v_preguntas
  from viabilidad_preguntas p
  join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
  where s.plantilla_id = p_plantilla_id and p.activa = true;
  if v_preguntas = 0 then
    v_errores := v_errores || jsonb_build_array(jsonb_build_object(
      'codigo','sin_preguntas','mensaje','La plantilla no tiene preguntas activas'));
  end if;

  select array_agg(p.codigo) into v_codigos
  from viabilidad_preguntas p
  join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
  where s.plantilla_id = p_plantilla_id;

  select string_agg(codigo, ', ') into v_dup from (
    select p.codigo
    from viabilidad_preguntas p
    join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
    where s.plantilla_id = p_plantilla_id
    group by p.codigo
    having count(*) > 1
  ) d;
  if v_dup is not null then
    v_errores := v_errores || jsonb_build_array(jsonb_build_object(
      'codigo','codigo_duplicado','ref', v_dup,
      'mensaje', format('Códigos de pregunta duplicados en la plantilla: %s', v_dup)));
  end if;

  for rec in
    select p.* from viabilidad_preguntas p
    join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
    where s.plantilla_id = p_plantilla_id
  loop
    if rec.codigo is null or btrim(rec.codigo) = '' then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','pregunta_sin_codigo','ref', rec.id_pregunta_viabilidad::text,
        'mensaje','Hay una pregunta sin código'));
    end if;
    if rec.texto is null or btrim(rec.texto) = '' then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','pregunta_sin_texto','ref', rec.codigo,
        'mensaje', format('La pregunta "%s" no tiene texto', coalesce(rec.codigo, rec.id_pregunta_viabilidad::text))));
    end if;
    if rec.tipo_respuesta not in
       ('booleano','opcion_unica','opcion_multiple','numero','texto','fecha','evidencia') then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','tipo_invalido','ref', rec.codigo,
        'mensaje', format('La pregunta "%s" usa un tipo de respuesta no soportado', rec.codigo)));
    end if;

    if rec.evidencia_tipo is not null and rec.evidencia_tipo not in ('foto','documento','foto_o_documento') then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','evidencia_tipo_invalido','ref', rec.codigo,
        'mensaje', format('La pregunta "%s" usa un tipo de evidencia no soportado', rec.codigo)));
    end if;

    if rec.evidencia_obligatoria_condicion is not null then
      if rec.evidencia_tipo is null then
        v_errores := v_errores || jsonb_build_array(jsonb_build_object(
          'codigo','evidencia_condicion_sin_tipo','ref', rec.codigo,
          'mensaje', format('La pregunta "%s" condiciona una evidencia que no está configurada', rec.codigo)));
      end if;
      v_err := public._viabilidad_expr_error(rec.evidencia_obligatoria_condicion, v_codigos);
      if v_err is not null then
        v_errores := v_errores || jsonb_build_array(jsonb_build_object(
          'codigo','evidencia_condicion_invalida','ref', rec.codigo,
          'mensaje', format('Condición de evidencia de "%s": %s', rec.codigo, v_err)));
      end if;
    end if;

    if rec.activa and rec.tipo_respuesta in ('opcion_unica','opcion_multiple')
       and not exists (select 1 from viabilidad_opciones o where o.pregunta_id = rec.id_pregunta_viabilidad) then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','sin_opciones','ref', rec.codigo,
        'mensaje', format('La pregunta "%s" es de opción y no tiene opciones', rec.codigo)));
    end if;

    if rec.regla_evaluacion is not null then
      v_err := public._viabilidad_regla_error(rec.regla_evaluacion);
      if v_err is not null then
        v_errores := v_errores || jsonb_build_array(jsonb_build_object(
          'codigo','regla_invalida','ref', rec.codigo,
          'mensaje', format('Regla de la pregunta "%s": %s', coalesce(rec.codigo, rec.id_pregunta_viabilidad::text), v_err)));
      end if;
    end if;
  end loop;

  for rec in
    select o.* from viabilidad_opciones o
    join viabilidad_preguntas p on p.id_pregunta_viabilidad = o.pregunta_id
    join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
    where s.plantilla_id = p_plantilla_id
  loop
    if rec.valor is null or btrim(rec.valor) = '' or rec.etiqueta is null or btrim(rec.etiqueta) = '' then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','opcion_invalida','ref', rec.id_opcion_viabilidad::text,
        'mensaje','Hay una opción sin valor o sin etiqueta'));
    end if;
    if rec.regla is not null then
      v_err := public._viabilidad_regla_error(rec.regla);
      if v_err is not null then
        v_errores := v_errores || jsonb_build_array(jsonb_build_object(
          'codigo','regla_opcion_invalida','ref', rec.id_opcion_viabilidad::text,
          'mensaje', format('Regla de la opción "%s": %s', rec.etiqueta, v_err)));
      end if;
    end if;
  end loop;

  for rec in
    select c.* from viabilidad_condiciones c
    join viabilidad_preguntas p on p.id_pregunta_viabilidad = c.pregunta_id
    join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
    where s.plantilla_id = p_plantilla_id
  loop
    if not exists (
      select 1 from viabilidad_preguntas p2
      join viabilidad_secciones s2 on s2.id_seccion_viabilidad = p2.seccion_id
      where p2.id_pregunta_viabilidad = rec.pregunta_origen_id
        and s2.plantilla_id = p_plantilla_id
    ) then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','condicion_origen_inexistente','ref', rec.id_condicion_viabilidad::text,
        'mensaje','Una condición apunta a una pregunta origen fuera de la plantilla'));
    end if;

    if (select p2.tipo_respuesta from viabilidad_preguntas p2
          where p2.id_pregunta_viabilidad = rec.pregunta_origen_id) in ('opcion_unica','opcion_multiple')
       and rec.operador in ('=','!=','contiene','in','not_in') then
      foreach v_val in array string_to_array(coalesce(rec.valor,''), ',') loop
        if btrim(v_val) <> '' and not exists (
          select 1 from viabilidad_opciones o
           where o.pregunta_id = rec.pregunta_origen_id and o.valor = btrim(v_val)
        ) then
          v_errores := v_errores || jsonb_build_array(jsonb_build_object(
            'codigo','condicion_valor_inexistente','ref', rec.id_condicion_viabilidad::text,
            'mensaje', format('La condición referencia la opción inexistente "%s"', btrim(v_val))));
        end if;
      end loop;
    end if;
  end loop;

  -- Reglas multicriterio a nivel plantilla.
  for rec in select * from viabilidad_reglas where plantilla_id = p_plantilla_id loop
    if rec.severidad_funcional not in
       ('bloqueante','requiere_especialista','observacion','informativa') then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','regla_severidad_invalida','ref', rec.codigo,
        'mensaje', format('La regla "%s" usa una severidad no soportada', rec.codigo)));
    end if;
    if rec.efecto_funcional not in
       ('no_apto','validacion_especializada','accion_requerida','observacion','informativa') then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','regla_efecto_invalido','ref', rec.codigo,
        'mensaje', format('La regla "%s" usa un efecto no soportado', rec.codigo)));
    end if;
    if rec.efecto_funcional = 'validacion_especializada'
       and (rec.validacion_tipo is null or rec.validacion_tipo not in
            ('estructural','electrico','legal','cfe','otro')) then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','regla_validacion_invalida','ref', rec.codigo,
        'mensaje', format('La regla "%s" requiere un tipo de validación válido', rec.codigo)));
    end if;
    v_err := public._viabilidad_expr_error(rec.cuando, v_codigos);
    if v_err is not null then
      v_errores := v_errores || jsonb_build_array(jsonb_build_object(
        'codigo','regla_condicion_invalida','ref', rec.codigo,
        'mensaje', format('Condición de la regla "%s": %s', rec.codigo, v_err)));
    end if;
  end loop;

  select public._viabilidad_dependencias_ciclicas(p_plantilla_id) into v_ciclo;
  if v_ciclo then
    v_errores := v_errores || jsonb_build_array(jsonb_build_object(
      'codigo','dependencias_ciclicas',
      'mensaje','Existen dependencias circulares entre condiciones que el motor no puede resolver'));
  end if;

  return jsonb_build_object(
    'ok', jsonb_array_length(v_errores) = 0,
    'errores', v_errores
  );
end;
$$;

-- Versionado: clona columnas nuevas y las reglas multicriterio.
create or replace function public.crear_version_plantilla_viabilidad(
  p_origen_id integer,
  p_operation_id uuid default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_cached jsonb;
  v_origen record;
  v_version integer;
  v_id integer;
  rec record;
  v_new integer;
begin
  if not public.es_admin() then raise exception 'Solo un administrador puede gestionar plantillas'; end if;
  if p_operation_id is not null then
    v_cached := public._idempotente_leer(p_operation_id);
    if v_cached is not null then return v_cached; end if;
  end if;

  select * into v_origen from viabilidad_plantillas
   where id_plantilla_viabilidad = p_origen_id;
  if not found then raise exception 'La plantilla % no existe', p_origen_id; end if;

  perform set_config('zyra.rpc_plantilla', 'on', true);

  select coalesce(max(version), 0) + 1 into v_version
  from viabilidad_plantillas
  where empresa_id = v_origen.empresa_id
    and servicio_id is not distinct from v_origen.servicio_id
    and tipo_etapa = v_origen.tipo_etapa;

  insert into viabilidad_plantillas(empresa_id, servicio_id, tipo_etapa, version, nombre, estado, creado_por)
  values (v_origen.empresa_id, v_origen.servicio_id, v_origen.tipo_etapa, v_version,
          v_origen.nombre, 'borrador', auth.uid())
  returning id_plantilla_viabilidad into v_id;

  drop table if exists _vpl_map_sec;
  drop table if exists _vpl_map_preg;
  create temporary table _vpl_map_sec(old integer primary key, new integer) on commit drop;
  create temporary table _vpl_map_preg(old integer primary key, new integer) on commit drop;

  for rec in select * from viabilidad_secciones where plantilla_id = p_origen_id order by orden, id_seccion_viabilidad loop
    insert into viabilidad_secciones(plantilla_id, orden, codigo, titulo, descripcion)
    values (v_id, rec.orden, rec.codigo, rec.titulo, rec.descripcion)
    returning id_seccion_viabilidad into v_new;
    insert into _vpl_map_sec(old, new) values (rec.id_seccion_viabilidad, v_new);
  end loop;

  for rec in
    select p.* from viabilidad_preguntas p
    join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
    where s.plantilla_id = p_origen_id
    order by p.orden, p.id_pregunta_viabilidad
  loop
    insert into viabilidad_preguntas(
      seccion_id, orden, codigo, texto, ayuda, tipo_respuesta, obligatoria, regla_evaluacion, activa,
      unidad, evidencia_tipo, evidencia_obligatoria, evidencia_obligatoria_condicion, evidencia_instruccion)
    values ((select new from _vpl_map_sec where old = rec.seccion_id),
            rec.orden, rec.codigo, rec.texto, rec.ayuda, rec.tipo_respuesta,
            rec.obligatoria, rec.regla_evaluacion, rec.activa,
            rec.unidad, rec.evidencia_tipo, rec.evidencia_obligatoria,
            rec.evidencia_obligatoria_condicion, rec.evidencia_instruccion)
    returning id_pregunta_viabilidad into v_new;
    insert into _vpl_map_preg(old, new) values (rec.id_pregunta_viabilidad, v_new);

    insert into viabilidad_opciones(pregunta_id, orden, valor, etiqueta, regla)
    select v_new, o.orden, o.valor, o.etiqueta, o.regla
    from viabilidad_opciones o where o.pregunta_id = rec.id_pregunta_viabilidad;
  end loop;

  insert into viabilidad_condiciones(pregunta_id, pregunta_origen_id, operador, valor, accion)
  select (select new from _vpl_map_preg where old = c.pregunta_id),
         (select new from _vpl_map_preg where old = c.pregunta_origen_id),
         c.operador, c.valor, c.accion
  from viabilidad_condiciones c
  join viabilidad_preguntas p on p.id_pregunta_viabilidad = c.pregunta_id
  join viabilidad_secciones s on s.id_seccion_viabilidad = p.seccion_id
  where s.plantilla_id = p_origen_id;

  insert into viabilidad_reglas(
    plantilla_id, orden, etiqueta, codigo, severidad_funcional, efecto_funcional,
    cuando, mensaje, accion_o_tipo, validacion_tipo)
  select v_id, orden, etiqueta, codigo, severidad_funcional, efecto_funcional,
         cuando, mensaje, accion_o_tipo, validacion_tipo
  from viabilidad_reglas where plantilla_id = p_origen_id;

  insert into audit_log(usuario_id, empleado_id, accion, entidad, entidad_id, valores_nuevos)
  values (auth.uid(), public.mi_empleado_id(), 'crear_version_plantilla_viabilidad', 'viabilidad_plantillas',
          v_id::text, jsonb_build_object('origen_id', p_origen_id, 'version', v_version));

  v_cached := jsonb_build_object('id_plantilla_viabilidad', v_id, 'origen_id', p_origen_id,
                                 'version', v_version, 'estado', 'borrador');
  if p_operation_id is not null then
    perform public._idempotente_guardar(p_operation_id, 'crear_version_plantilla_viabilidad', v_cached);
  end if;
  return v_cached;
end;
$$;

