create extension if not exists pgcrypto;

-- ─────────────────────────────────────────────────────────────────────
-- Tablas de referencia
-- ─────────────────────────────────────────────────────────────────────

create table if not exists roles (
  id_rol        integer generated by default as identity primary key,
  nombre_rol    text not null unique,
  descripcion   text,
  creado_en     timestamptz not null default now()
);

create table if not exists empresas (
  id_empresa    integer generated by default as identity primary key,
  nombre        text not null,
  direccion     text,
  correo        text,
  telefono      text,
  creado_en     timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────────────
-- Personas y usuarios
-- ─────────────────────────────────────────────────────────────────────

create table if not exists empleados (
  id_empleado    integer generated by default as identity primary key,
  empresa_id     integer not null references empresas(id_empresa) on delete restrict,
  nombre         text not null,
  telefono       text,
  correo         text,
  activo         boolean not null default true,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_empleados_empresa on empleados(empresa_id);

-- usuarios.id_usuario es el mismo id que auth.users.id
create table if not exists usuarios (
  id_usuario     uuid primary key references auth.users(id) on delete cascade,
  empleado_id    integer unique references empleados(id_empleado) on delete set null,
  rol_id         integer not null references roles(id_rol) on delete restrict,
  username       text not null unique,
  activo         boolean not null default true,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_usuarios_empleado on usuarios(empleado_id);
create index if not exists idx_usuarios_rol on usuarios(rol_id);

-- ─────────────────────────────────────────────────────────────────────
-- Equipos / cuadrillas
-- ─────────────────────────────────────────────────────────────────────

create table if not exists equipos (
  id_equipo      integer generated by default as identity primary key,
  empresa_id     integer not null references empresas(id_empresa) on delete restrict,
  nombre_equipo  text not null,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_equipos_empresa on equipos(empresa_id);

create table if not exists empleado_equipo (
  empleado_id  integer not null references empleados(id_empleado) on delete cascade,
  equipo_id    integer not null references equipos(id_equipo) on delete cascade,
  cargo        text,
  es_lider     boolean not null default false,
  creado_en    timestamptz not null default now(),
  primary key (empleado_id, equipo_id)
);
create index if not exists idx_empleado_equipo_equipo on empleado_equipo(equipo_id);

-- ─────────────────────────────────────────────────────────────────────
-- Catálogos
-- ─────────────────────────────────────────────────────────────────────

create table if not exists clientes (
  id_cliente     integer generated by default as identity primary key,
  empresa_id     integer not null references empresas(id_empresa) on delete restrict,
  nombre         text not null,
  razon_social   text,
  correo         text,
  direccion      text,
  telefono       text,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_clientes_empresa on clientes(empresa_id);
-- Evitar duplicados por correo (cuando exista)
create unique index if not exists uq_clientes_correo on clientes(lower(correo)) where correo is not null and correo <> '';

create table if not exists servicios (
  id_servicio    integer generated by default as identity primary key,
  empresa_id     integer not null references empresas(id_empresa) on delete restrict,
  tipo           text not null,
  descripcion    text,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists idx_servicios_empresa on servicios(empresa_id);

create table if not exists materiales (
  id_material       integer generated by default as identity primary key,
  empresa_id        integer not null references empresas(id_empresa) on delete restrict,
  nombre_material   text not null,
  unidad            text,
  stock_disponible  integer not null default 0,
  creado_en         timestamptz not null default now(),
  actualizado_en    timestamptz not null default now(),
  constraint chk_materiales_stock_no_negativo check (stock_disponible >= 0)
);
create index if not exists idx_materiales_empresa on materiales(empresa_id);

-- ─────────────────────────────────────────────────────────────────────
-- Plantillas de checklist por servicio
-- ─────────────────────────────────────────────────────────────────────

create table if not exists checklist_servicio (
  id_checklist_servicio integer generated by default as identity primary key,
  empresa_id            integer not null references empresas(id_empresa) on delete restrict,
  servicio_id           integer references servicios(id_servicio) on delete cascade,
  nombre                text not null,
  creado_en             timestamptz not null default now()
);
create index if not exists idx_checklist_servicio_servicio on checklist_servicio(servicio_id);

create table if not exists checklist_servicio_detalle (
  id_checklist_servicio_detalle integer generated by default as identity primary key,
  checklist_servicio_id         integer not null references checklist_servicio(id_checklist_servicio) on delete cascade,
  material_id                   integer not null references materiales(id_material) on delete restrict,
  cantidad_requerida            integer not null default 0,
  unique (checklist_servicio_id, material_id),
  constraint chk_csd_cantidad check (cantidad_requerida >= 0)
);
create index if not exists idx_csd_servicio on checklist_servicio_detalle(checklist_servicio_id);

-- ─────────────────────────────────────────────────────────────────────
-- Proyectos
-- ─────────────────────────────────────────────────────────────────────

create table if not exists proyectos (
  id_proyecto     integer generated by default as identity primary key,
  empresa_id      integer not null references empresas(id_empresa) on delete restrict,
  cliente_id      integer references clientes(id_cliente) on delete set null,
  servicio_id     integer references servicios(id_servicio) on delete set null,
  equipo_id       integer references equipos(id_equipo) on delete set null,
  nombre_proyecto text not null,
  ubicacion       text,
  fecha_inicio    date,
  fecha_fin       date,
  estado          text not null default 'borrador',
  imagen_url      text,
  version         integer not null default 1,
  creado_por      uuid references usuarios(id_usuario) on delete set null,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now(),
  constraint chk_proyectos_estado check (estado in (
    'borrador','preparacion','checklist_pendiente','listo_para_iniciar',
    'en_proceso','pendiente_de_cierre','finalizado','cancelado','rechazado'
  )),
  constraint chk_proyectos_fechas check (
    fecha_fin is null or fecha_inicio is null or fecha_fin >= fecha_inicio
  )
);
create index if not exists idx_proyectos_empresa on proyectos(empresa_id);
create index if not exists idx_proyectos_cliente on proyectos(cliente_id);
create index if not exists idx_proyectos_servicio on proyectos(servicio_id);
create index if not exists idx_proyectos_equipo on proyectos(equipo_id);
create index if not exists idx_proyectos_estado on proyectos(estado);

-- Materiales planificados de un proyecto
create table if not exists proyecto_materiales (
  id_proyecto_material integer generated by default as identity primary key,
  proyecto_id          integer not null references proyectos(id_proyecto) on delete cascade,
  material_id          integer not null references materiales(id_material) on delete restrict,
  cantidad_requerida   integer not null default 0,
  creado_en            timestamptz not null default now(),
  unique (proyecto_id, material_id),
  constraint chk_pm_cantidad check (cantidad_requerida >= 0)
);
create index if not exists idx_pm_proyecto on proyecto_materiales(proyecto_id);

-- Checklist físico de verificación (uno por proyecto)
create table if not exists checklists (
  id_checklist    integer generated by default as identity primary key,
  proyecto_id     integer not null unique references proyectos(id_proyecto) on delete cascade,
  estado          text not null default 'pendiente',
  verificado_por  integer references empleados(id_empleado) on delete set null,
  verificado_en   timestamptz,
  observaciones   text,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now(),
  constraint chk_checklists_estado check (estado in ('pendiente','completo','incompleto'))
);

create table if not exists checklist_detalle (
  id_checklist_detalle integer generated by default as identity primary key,
  checklist_id         integer not null references checklists(id_checklist) on delete cascade,
  material_id          integer not null references materiales(id_material) on delete restrict,
  cantidad_requerida   integer not null default 0,
  cantidad_cargada     integer not null default 0,
  marcado              boolean not null default false,
  empleado_id          integer references empleados(id_empleado) on delete set null,
  observaciones        text,
  actualizado_en       timestamptz not null default now(),
  unique (checklist_id, material_id),
  constraint chk_cd_cantidades check (cantidad_requerida >= 0 and cantidad_cargada >= 0)
);
create index if not exists idx_cd_checklist on checklist_detalle(checklist_id);

-- ─────────────────────────────────────────────────────────────────────
-- Ejecución: avances (diario), evidencias, reportes, puntos
-- ─────────────────────────────────────────────────────────────────────

create table if not exists avances (
  id_avance     integer generated by default as identity primary key,
  proyecto_id   integer not null references proyectos(id_proyecto) on delete cascade,
  empleado_id   integer references empleados(id_empleado) on delete set null,
  descripcion   text not null,
  porcentaje    integer,
  operation_id  uuid unique,
  creado_en     timestamptz not null default now(),
  constraint chk_avances_porcentaje check (porcentaje is null or (porcentaje >= 0 and porcentaje <= 100))
);
create index if not exists idx_avances_proyecto on avances(proyecto_id);

create table if not exists evidencias (
  id_evidencia  uuid primary key default gen_random_uuid(),
  proyecto_id   integer not null references proyectos(id_proyecto) on delete cascade,
  empleado_id   integer references empleados(id_empleado) on delete set null,
  avance_id     integer references avances(id_avance) on delete set null,
  object_key    text not null,
  descripcion   text,
  tipo          text not null default 'foto',
  content_type  text,
  size_bytes    bigint,
  fecha         timestamptz not null default now(),
  creado_en     timestamptz not null default now(),
  eliminado     boolean not null default false,
  constraint chk_evidencias_tipo check (tipo in ('foto','documento','video'))
);
create index if not exists idx_evidencias_proyecto on evidencias(proyecto_id);
create index if not exists idx_evidencias_empleado on evidencias(empleado_id);

create table if not exists reportes (
  id_reporte      integer generated by default as identity primary key,
  proyecto_id     integer references proyectos(id_proyecto) on delete set null,
  equipo_id       integer references equipos(id_equipo) on delete set null,
  empleado_id     integer references empleados(id_empleado) on delete set null,
  comentarios     text,
  estado          text not null default 'pendiente',
  numero_reporte  text unique,
  es_final        boolean not null default false,
  version         integer not null default 1,
  fecha_reporte   timestamptz not null default now(),
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now(),
  constraint chk_reportes_estado check (estado in ('pendiente','aprobado','rechazado'))
);
create index if not exists idx_reportes_proyecto on reportes(proyecto_id);
create index if not exists idx_reportes_estado on reportes(estado);

create table if not exists puntos_historial (
  id_punto          integer generated by default as identity primary key,
  empleado_id       integer not null references empleados(id_empleado) on delete cascade,
  proyecto_id       integer references proyectos(id_proyecto) on delete cascade,
  cantidad_puntos   integer not null,
  motivo            text,
  tipo_evento       text not null,
  operation_id      uuid unique,
  fecha             timestamptz not null default now()
);
create index if not exists idx_puntos_empleado on puntos_historial(empleado_id);
create index if not exists idx_puntos_proyecto on puntos_historial(proyecto_id);
-- Idempotencia: un evento por empleado+proyecto. Para eventos sin proyecto se
-- usa operation_id único.
create unique index if not exists uq_puntos_evento
  on puntos_historial(empleado_id, proyecto_id, tipo_evento)
  where proyecto_id is not null;

-- ─────────────────────────────────────────────────────────────────────
-- Recordatorios
-- ─────────────────────────────────────────────────────────────────────

create table if not exists recordatorios (
  id_recordatorio integer generated by default as identity primary key,
  empresa_id      integer not null references empresas(id_empresa) on delete restrict,
  titulo          text not null,
  descripcion     text,
  fecha           date,
  hora            time,
  activo          boolean not null default true,
  creado_por      uuid references usuarios(id_usuario) on delete set null,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now()
);
create index if not exists idx_recordatorios_empresa on recordatorios(empresa_id);

create table if not exists recordatorio_destinatarios (
  recordatorio_id integer not null references recordatorios(id_recordatorio) on delete cascade,
  empleado_id     integer not null references empleados(id_empleado) on delete cascade,
  leido           boolean not null default false,
  leido_en        timestamptz,
  primary key (recordatorio_id, empleado_id)
);

-- ─────────────────────────────────────────────────────────────────────
-- Auditoría (inmutable)
-- ─────────────────────────────────────────────────────────────────────

create table if not exists audit_log (
  id_audit          bigint generated by default as identity primary key,
  usuario_id        uuid references usuarios(id_usuario) on delete set null,
  empleado_id       integer references empleados(id_empleado) on delete set null,
  accion            text not null,
  entidad           text not null,
  entidad_id        text,
  valores_anteriores jsonb,
  valores_nuevos     jsonb,
  fecha             timestamptz not null default now()
);
create index if not exists idx_audit_entidad on audit_log(entidad, entidad_id);
create index if not exists idx_audit_usuario on audit_log(usuario_id);

-- Idempotencia genérica de operaciones (outbox / reintentos)
create table if not exists operaciones_procesadas (
  operation_id uuid primary key,
  tipo         text,
  resultado    jsonb,
  creado_en    timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────────────
-- Trigger: actualizar actualizado_en
-- ─────────────────────────────────────────────────────────────────────

create or replace function public.set_actualizado_en()
returns trigger
language plpgsql
as $$
begin
  new.actualizado_en := now();
  return new;
end;
$$;

do $$
declare
  t text;
  tablas text[] := array[
    'empresas','empleados','usuarios','equipos','clientes','servicios',
    'materiales','proyectos','checklists','reportes','recordatorios'
  ];
begin
  foreach t in array tablas loop
    execute format('drop trigger if exists trg_%1$s_actualizado on %1$s', t);
    execute format(
      'create trigger trg_%1$s_actualizado before update on %1$s
       for each row execute function public.set_actualizado_en()', t);
  end loop;
end $$;
